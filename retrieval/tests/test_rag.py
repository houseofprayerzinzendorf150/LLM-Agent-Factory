# === Integration-style tests (with mocked external calls) ===


class TestRAGIntegration:
    """Integration-style tests for the RAG system."""

    @patch("retrieval.rag.AgentRetriever")
    @patch("retrieval.rag.OpenAI")
    def test_full_generate_flow(self, mock_openai, mock_retriever):
        """Test the full generation flow."""
        # Setup retriever mock
        mock_retriever_instance = Mock()
        mock_retriever_instance.search.return_value = [
            RetrievalResult(
                agent=AgentSpec(
                    agent_id="similar_agent",
                    display_name="Similar Agent",
                    persona="A similar agent for context",
                    description="This is a similar agent",
                    tools=["tool"],
                ),
                score=0.9,
                rank=1,
            )
        ]
        mock_retriever.return_value = mock_retriever_instance

        # Setup LLM mock
        mock_client = Mock()
        generated_response = json.dumps(
            {
                "agent_id": "new_agent",
                "display_name": "New Agent",
                "persona": "A newly created agent",
                "description": "Created based on the query",
                "tools": ["new_tool"],
            }
        )
        mock_response = Mock()
        mock_response.choices = [Mock(message=Mock(content=generated_response))]
        mock_client.chat.completions.create.return_value = mock_response
        mock_openai.return_value = mock_client

        # Run the test
        config = RAGConfig(
            num_agents_to_return=1,
            num_retrieved_for_context=3,
        )
        rag = AgentRAG(config)

        agents = rag.generate("I need a code review agent")

        # Verify
        assert len(agents) == 1
        assert agents[0]["agent_id"] == "new_agent"

        # Check that retriever was called with correct params
        mock_retriever_instance.search.assert_called_with(
            "I need a code review agent",
            top_k=3,
        )

        # Check that LLM was called
        call_args = mock_client.chat.completions.create.call_args
        assert call_args.kwargs["model"] == "gpt-oss"
        assert len(call_args.kwargs["messages"]) == 2
        assert call_args.kwargs["messages"][0]["role"] == "system"
        assert call_args.kwargs["messages"][1]["role"] == "user"

    @patch("retrieval.rag.AgentRetriever")
    @patch("retrieval.rag.OpenAI")
    def test_generate_multiple_agents(self, mock_openai, mock_retriever):
        """Test generating multiple agents."""
        mock_retriever_instance = Mock()
        mock_retriever_instance.search.return_value = []
        mock_retriever.return_value = mock_retriever_instance

        mock_client = Mock()
        mock_response = Mock()
        mock_response.choices = [Mock(message=Mock(content=SAMPLE_LLM_RESPONSE_MULTI))]
        mock_client.chat.completions.create.return_value = mock_response
        mock_openai.return_value = mock_client

        config = RAGConfig(num_agents_to_return=2)
        rag = AgentRAG(config)

        agents = rag.generate("create agents")

        assert len(agents) == 2



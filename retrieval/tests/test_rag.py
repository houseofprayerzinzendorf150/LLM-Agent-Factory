# === Tests for build_prompt ===


class TestBuildPrompt:
    """Tests for the build_prompt function."""

    def test_build_prompt_with_examples(self):
        """Test prompt building with examples."""
        examples = [SAMPLE_RETRIEVAL_RESULT]
        prompt = build_prompt("create a test agent", examples, num_agents=1)

        assert "create a test agent" in prompt
        assert "Test Agent" in prompt
        assert "test_agent" in prompt
        assert "Example 1:" in prompt
        assert "Generate ONE agent" in prompt

    def test_build_prompt_without_examples(self):
        """Test prompt building without examples."""
        prompt = build_prompt("create a test agent", [], num_agents=1)

        assert "create a test agent" in prompt
        assert "Example" not in prompt
        assert "Generate ONE agent" in prompt

    def test_build_prompt_multiple_agents(self):
        """Test prompt for multiple agent generation."""
        prompt = build_prompt("create agents", [], num_agents=3)

        assert "Generate 3 different agent specifications" in prompt
        assert "JSON array" in prompt

    def test_build_prompt_multiple_examples(self):
        """Test prompt with multiple examples."""
        examples = [
            RetrievalResult(agent=SAMPLE_AGENT, score=0.95, rank=1),
            RetrievalResult(
                agent=AgentSpec(
                    agent_id="second_agent",
                    display_name="Second Agent",
                    persona="Another agent",
                    description="Another description",
                    tools=[],
                ),
                score=0.85,
                rank=2,
            ),
        ]
        prompt = build_prompt("query", examples)

        assert "Example 1:" in prompt
        assert "Example 2:" in prompt
        assert "Test Agent" in prompt
        assert "Second Agent" in prompt


# === Tests for parse_agent_response ===


class TestParseAgentResponse:
    """Tests for the parse_agent_response function."""

    def test_parse_single_agent(self):
        """Test parsing a single agent response."""
        agents = parse_agent_response(SAMPLE_LLM_RESPONSE)

        assert len(agents) == 1
        assert agents[0]["agent_id"] == "generated_agent"
        assert agents[0]["display_name"] == "Generated Agent"

    def test_parse_multiple_agents(self):
        """Test parsing multiple agents response."""
        agents = parse_agent_response(SAMPLE_LLM_RESPONSE_MULTI)

        assert len(agents) == 2
        assert agents[0]["agent_id"] == "agent_1"
        assert agents[1]["agent_id"] == "agent_2"

    def test_parse_with_markdown_json_block(self):
        """Test parsing response wrapped in markdown code block."""
        response = f"```json\n{SAMPLE_LLM_RESPONSE}\n```"
        agents = parse_agent_response(response)

        assert len(agents) == 1
        assert agents[0]["agent_id"] == "generated_agent"

    def test_parse_with_markdown_block(self):
        """Test parsing response wrapped in generic markdown block."""
        response = f"```\n{SAMPLE_LLM_RESPONSE}\n```"
        agents = parse_agent_response(response)

        assert len(agents) == 1
        assert agents[0]["agent_id"] == "generated_agent"

    def test_parse_invalid_json_raises(self):
        """Test that invalid JSON raises ValueError."""
        with pytest.raises(ValueError) as exc_info:
            parse_agent_response("not valid json")

        assert "Failed to parse LLM response" in str(exc_info.value)

    def test_parse_with_whitespace(self):
        """Test parsing response with extra whitespace."""
        response = f"  \n\n{SAMPLE_LLM_RESPONSE}\n\n  "
        agents = parse_agent_response(response)

        assert len(agents) == 1


